// Journal
const { start, ok } = require('./common');
(async () => {
  const t = await start({ time: '2026-11-16T21:30:00+01:00' });
  const { p, T, W, texts, shot, L } = t;
  const reload = async () => { await p.reload(); await p.waitForSelector('body.ready'); await L.decorate(p); await W(350); };

  console.log('Schreiben');
  await T('[data-tab="journal"]'); await W(450);
  ok((await texts('#j-date'))[0] === 'Montag, 16. November', 'Datum: ' + (await texts('#j-date'))[0]);
  const qs = await texts('#j-editor .jq');
  ok(qs.join('|') === 'Was habe ich heute gelernt oder erkannt?|Was lief gut, was nicht?|Freie Gedanken', 'drei Felder mit den richtigen Fragen');
  ok(await p.evaluate(() => document.querySelector('#j-save').getAttribute('aria-disabled') === 'true'), 'Speichern ist bei leerem Eintrag inaktiv');
  await T('#j-editor textarea', 0); await W(600);
  await p.keyboard.type('Dass der Anfang die eigentliche Hürde ist. Nach zehn Minuten am Klavier lief es von selbst.');
  await W(300); await shot('50-journal-schreiben');
  const h1 = await p.evaluate(() => document.querySelectorAll('#j-editor textarea')[0].getBoundingClientRect().height);
  await p.keyboard.type('\nNoch ein Gedanke dazu: kleine Schritte zählen mehr als große Pläne. '.repeat(6));
  await W(300);
  const h2 = await p.evaluate(() => document.querySelectorAll('#j-editor textarea')[0].getBoundingClientRect().height);
  ok(h2 > h1 + 100, 'Feld wächst mit (' + Math.round(h1) + ' → ' + Math.round(h2) + ' px)');
  const vis = await p.evaluate(() => { const ta = document.activeElement, r = ta.getBoundingClientRect(); return { bottom: Math.round(r.bottom), limit: document.documentElement.clientHeight - 336 }; });
  ok(vis.bottom <= vis.limit, 'Textende bleibt über der Tastatur sichtbar (' + vis.bottom + ' ≤ ' + vis.limit + ')');
  await shot('51-journal-lang');
  ok(await p.evaluate(() => { const ta = document.activeElement; return ta.scrollHeight <= ta.clientHeight + 1; }), 'kein innerer Scrollbalken im Feld');
  await p.evaluate(() => document.activeElement.blur()); await W(400);
  await T('#j-editor textarea', 1); await W(500);
  await p.keyboard.type('Gut: früh aufgestanden, Sport gemacht. Nicht gut: abends zu lange am Handy.');
  await p.evaluate(() => document.activeElement.blur()); await W(600);

  console.log('Automatisch gesichert');
  await reload();
  await T('[data-tab="journal"]'); await W(400);
  ok((await p.inputValue('#j-editor textarea >> nth=1')).startsWith('Gut: früh aufgestanden'), 'Text übersteht Neuladen ohne „Speichern“');

  console.log('Speichern + Angebot');
  await p.evaluate(() => document.querySelector('#v-journal .scroll').scrollTo(0, 1e5)); await W(200);
  await T('#j-editor textarea', 2); await W(500);
  await p.keyboard.type('Morgen zuerst die Bewerbung.'); await W(200);
  await T('#j-save'); await W(800);
  ok(await p.evaluate(() => document.querySelector('#L-offer').classList.contains('open')), 'nach Speichern kommt das Angebot');
  ok((await texts('#offer-text'))[0] === 'Morgen planen?', 'Text: ' + (await texts('#offer-text'))[0]);
  await shot('52-journal-angebot');
  await T('#offer-go'); await W(800);
  ok(await p.evaluate(() => document.querySelector('#L-plan').classList.contains('open') && !document.querySelector('#L-offer').classList.contains('open')), '„Morgen planen“ öffnet „Tag planen“');
  ok((await texts('#plan-date'))[0].startsWith('Dienstag, 17. November'), 'vorgewählt ist morgen: ' + (await texts('#plan-date'))[0]);
  await shot('53-plan-morgen-aus-journal');
  await T('#plan-input'); await W(500); await p.keyboard.type('Bewerbung abschicken'); await p.keyboard.press('Enter'); await W(300);
  await T('#L-plan .sheet-foot .btn'); await W(700);
  await T('#j-save'); await W(700);
  ok((await texts('#offer-text'))[0] === 'Morgen ist schon geplant.', 'beim zweiten Speichern: ' + (await texts('#offer-text'))[0]);
  await T('#L-offer [data-act="closeTop"]'); await W(600);

  console.log('Frühere Einträge');
  ok((await texts('#j-list .jempty')).length === 1, 'heute noch keine früheren Einträge (gestalteter Hinweis)');
  await t.jump('2026-11-17T20:00:00+01:00');
  ok((await texts('#j-date'))[0] === 'Dienstag, 17. November', 'neuer Tag, neuer leerer Eintrag');
  ok((await p.inputValue('#j-editor textarea >> nth=0')) === '', 'Felder sind leer');
  ok((await texts('#j-list .jitem-date'))[0] === 'Montag, 16. November', 'gestern steht unter „Frühere Einträge“');
  await T('#j-editor textarea', 0); await W(400); await p.keyboard.type('Zweiter Tag. Bewerbung ist raus, fühlt sich leicht an.'); await p.evaluate(() => document.activeElement.blur()); await W(500);
  await t.jump('2026-11-18T20:00:00+01:00');
  await T('#j-editor textarea', 2); await W(400); await p.keyboard.type('Dritter Tag. Lange am Hafen gefilmt.'); await p.evaluate(() => document.activeElement.blur()); await W(500);
  await t.jump('2026-11-19T09:00:00+01:00');
  const dates = await texts('#j-list .jitem-date');
  ok(dates.join('|') === 'Mittwoch, 18. November|Dienstag, 17. November|Montag, 16. November', 'chronologisch, neueste oben: ' + dates.join(' | '));
  await p.evaluate(() => document.querySelector('#v-journal .scroll').scrollTo(0, 1e5)); await W(300);
  await shot('54-journal-fruehere');

  console.log('Suche');
  await T('#j-search'); await W(500); await p.keyboard.type('hafen'); await W(300);
  ok((await texts('#j-list .jitem-date')).join() === 'Mittwoch, 18. November', 'Suche „hafen“ findet den 18.: ' + (await texts('#j-list .jitem-date')).join());
  ok((await texts('#j-list mark'))[0] === 'Hafen', 'Treffer ist markiert');
  await shot('55-journal-suche');
  await p.fill('#j-search', 'xyzxyz'); await W(300);
  ok((await texts('#j-list .jempty'))[0].includes('Nichts gefunden'), 'kein Treffer: ' + (await texts('#j-list .jempty'))[0]);
  await T('#j-clear'); await W(300);
  ok((await texts('#j-list .jitem-date')).length === 3, 'Suche geleert zeigt wieder alle');
  await p.fill('#j-search', 'bewerbung'); await W(300);
  ok((await texts('#j-list .jitem-date')).length === 2, 'Suche durchsucht alle drei Felder (2 Treffer)');
  await T('#j-clear'); await W(200); await p.evaluate(() => document.activeElement.blur()); await W(500);

  console.log('Früheren Eintrag öffnen');
  await T('#j-list .jitem', 2); await W(800); await shot('56-journal-eintrag');
  ok((await texts('#je-title'))[0] === 'Mo., 16. Nov.', 'Titel: ' + (await texts('#je-title'))[0]);
  ok((await p.inputValue('#je-editor textarea >> nth=2')) === 'Morgen zuerst die Bewerbung.', 'Inhalt da');
  await T('#je-editor textarea', 2); await W(500); await p.keyboard.type(' Und danach joggen.'); await W(200);
  await T('#L-jentry .sheet-foot .btn'); await W(700);
  await reload(); await T('[data-tab="journal"]'); await W(400);
  await T('#j-list .jitem', 2); await W(700);
  const jv = await p.inputValue('#je-editor textarea >> nth=2'); ok(jv.includes('Und danach joggen.'), 'Änderung am alten Eintrag gesichert: ' + jv);
  await p.evaluate(() => document.querySelector('#L-jentry .sheet-body').scrollTo(0, 1e5)); await W(200);
  await T('[data-act="jeDelete"]'); await W(600); await shot('57-dialog-loeschen');
  await T('#dlg-cancel'); await W(500);
  ok(await p.evaluate(() => document.querySelector('#L-jentry').classList.contains('open')), 'Abbrechen lässt den Eintrag stehen');
  await T('[data-act="jeDelete"]'); await W(500); await T('#dlg-ok'); await W(700);
  ok((await texts('#j-list .jitem-date')).length === 2, 'Eintrag gelöscht');
  await reload(); await T('[data-tab="journal"]'); await W(400);
  ok((await texts('#j-list .jitem-date')).length === 2, 'bleibt nach Neuladen gelöscht');
  await t.end();
})().catch(e => { console.error('FAIL', e); process.exit(1); });
